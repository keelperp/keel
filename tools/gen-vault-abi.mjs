#!/usr/bin/env node
// The Vault UI's ABI is generated from forge's artefacts and pruned to what the component
// actually calls. A hand-copied slice drifts silently the moment a signature changes, and a
// gate that only counts arguments cannot see a type drift.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ART = join(ROOT, "out", "LeverVault.sol", "LeverVault.json");
if (!existsSync(ART)) {
  console.error(`\n  ABORT: ${ART} not found — run \`forge build\` first.\n`);
  process.exit(1);
}

// Exactly what Component.tsx reads and writes. Anything not listed is not shipped.
const USED = new Set([
  "nav", "currentLeverage", "healthBps", "pendingRevenue", "totalHarvested", "totalToProject",
  "totalReceived", "totalDeployed", "costBasis", "unrealisedGain", "positionUsd",
  "nextSettlementIn", "pendingAction", "pendingRequestId", "needsRebalance",
  "TARGET_LEVERAGE", "MIN_HEALTH_BPS", "PROJECT_SHARE_BPS",
  "deployPending", "harvest", "rebalance", "kickstart",
]);

const abi = JSON.parse(readFileSync(ART, "utf8")).abi;
const kept = abi.filter((e) => e.type === "function" && USED.has(e.name));
const missing = [...USED].filter((n) => !kept.some((e) => e.name === n));
if (missing.length) {
  console.error(`\n  ABORT: these names are not on LeverVault: ${missing.join(", ")}\n`);
  process.exit(1);
}

writeFileSync(
  join(ROOT, "vault-ui", "VaultABI.ts"),
  "// GENERATED by tools/gen-vault-abi.mjs from forge artefacts. Do not edit.\n" +
    "// Regenerate with `node tools/gen-vault-abi.mjs` after any contract change.\n\n" +
    `export const vaultAbi = ${JSON.stringify(kept, null, 2)} as const;\n`
);
console.log(`  wrote ${kept.length} entries -> vault-ui/VaultABI.ts`);
